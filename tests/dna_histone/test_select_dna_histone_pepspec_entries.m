function tests = test_select_dna_histone_pepspec_entries
tests = functiontests(localfunctions);
repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
dnaAutoDir = fullfile(repoRoot, 'dna_histone');
addpath(dnaAutoDir);
addpath(fullfile(repoRoot, 'common'));
end

function testLegacyUniquenessDropsEveryCollidingPsm(testCase)
entries = makeEntries( ...
    {'A1', 'A', 'B'}, ...
    {'23', '123', '7'}, ...
    {'PEPTIDEZ', 'PEPTIDEA', 'PEPTIDEM'}, ...
    {'Acetyl (K)', 'Methyl (K)', 'Dimethyl (K)'});

selected = select_dna_histone_pepspec_entries(entries);

verifyEqual(testCase, numel(selected), 1);
verifyEqual(testCase, selected.peptide, 'PEPTIDEM');
end

function testModificationPolicyKeepsOnlyInformativeModifications(testCase)
entries = makeEntries( ...
    {'A', 'B', 'C', 'D', 'E'}, ...
    {'1', '2', '3', '4', '5'}, ...
    {'UNMODIFIED', 'OXIDIZED', 'LABELONLY', 'LEGAL', 'LABELOTHER'}, ...
    { ...
        '-', ...
        'Oxidation (M),Acetyl (K)', ...
        'Label:13C(6) (K),Label:13C(6)15N(4) (R)', ...
        'Acetyl (K)', ...
        'Label:13C(6) (K),Methyl (K)'});

selected = select_dna_histone_pepspec_entries(entries);

verifyEqual(testCase, {selected.peptide}, {'LABELOTHER', 'LEGAL'});
end

function testSelectedEntriesArePeptideSortedAndInputIsUnchanged(testCase)
entries = makeEntries( ...
    {'dataset-C', 'dataset-A', 'dataset-B'}, ...
    {'30', '10', '20'}, ...
    {'PEPTIDEC', 'PEPTIDEA', 'PEPTIDEB'}, ...
    {'Trimethyl (K)', 'Acetyl (K)', 'Methyl (K)'});
originalEntries = entries;

selected = select_dna_histone_pepspec_entries(entries);

verifyEqual(testCase, {selected.peptide}, ...
    {'PEPTIDEA', 'PEPTIDEB', 'PEPTIDEC'});
verifyEqual(testCase, entries, originalEntries);
end

function entries = makeEntries(datasetNames, scans, peptides, modifications)
template = struct( ...
    'DatasetName', '', ...
    'Scan', '', ...
    'peptide', '', ...
    'modification', '', ...
    'Score', 100.0);
entries = repmat(template, size(datasetNames));
for idx = 1:numel(entries)
    entries(idx).DatasetName = datasetNames{idx};
    entries(idx).Scan = scans{idx};
    entries(idx).peptide = peptides{idx};
    entries(idx).modification = modifications{idx};
    entries(idx).Score = 100 + idx / 10;
end
end
