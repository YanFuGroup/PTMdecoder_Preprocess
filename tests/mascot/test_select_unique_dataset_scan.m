function testNonNumericScanTextIsHandledAsText(testCase)
result = makeResult( ...
    {'A', 'A', 'A', 'A'}, ...
    {'not-a-number', 'not-a-number', '+1', 'A-1'}, ...
    {'SYNPEPTIDEA', 'SYNPEPTIDEB', 'SYNPEPTIDEC', 'SYNPEPTIDED'});

selectedMask = select_unique_dataset_scan(result);

% Nonnumeric Scan text is never parsed. The two identical text values form
% a repeated legacy key, while '+1' and 'A-1' remain distinct.
verifyEqual(testCase, selectedMask, [false, false, true, true]);
end

