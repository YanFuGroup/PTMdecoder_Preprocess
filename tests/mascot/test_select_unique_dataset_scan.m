function setupOnce(testCase)
testCase.TestData.originalPath = path;
repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(fullfile(repoRoot, 'common'));
end

function teardownOnce(testCase)
path(testCase.TestData.originalPath);
end

function testNoDuplicateLegacyKeysAreAllSelected(testCase)
result = makeResult( ...
    {'dataset-A', 'dataset-A', 'dataset-B'}, ...
    {'101', '102', '101'}, ...
    {'SYNPEPTIDEA', 'SYNPEPTIDEB', 'SYNPEPTIDEC'});

selectedMask = select_unique_dataset_scan(result);

verifyEqual(testCase, selectedMask, [true, true, true]);
end

function testRepeatedLegacyKeyDropsEveryMember(testCase)
result = makeResult( ...
    {'dataset-A', 'dataset-A', 'dataset-A'}, ...
    {'101', '101', '102'}, ...
    {'SYNPEPTIDEA', 'SYNPEPTIDEB', 'SYNPEPTIDEC'});

selectedMask = select_unique_dataset_scan(result);

verifyEqual(testCase, selectedMask, [false, false, true]);
end

function testSameScanUnderDifferentDatasetsIsSelected(testCase)
result = makeResult( ...
    {'dataset-A', 'dataset-B', 'dataset-C'}, ...
    {'0017', '0017', 'not-a-number'}, ...
    {'SYNPEPTIDEA', 'SYNPEPTIDEB', 'SYNPEPTIDEC'});

selectedMask = select_unique_dataset_scan(result);

verifyEqual(testCase, selectedMask, [true, true, true]);
end

function testAllRepeatedLegacyKeysReturnsAllFalse(testCase)
result = makeResult( ...
    {'dataset-A', 'dataset-A', 'dataset-B', 'dataset-B'}, ...
    {'101', '101', '0017', '0017'}, ...
    {'SYNPEPTIDEA', 'SYNPEPTIDEB', 'SYNPEPTIDEC', 'SYNPEPTIDED'});

selectedMask = select_unique_dataset_scan(result);
filteredResult = result(selectedMask);

verifyEqual(testCase, selectedMask, [false, false, false, false]);
verifyEqual(testCase, numel(filteredResult), 0);
end

function testValidEmptyInputsPreserveShape(testCase)
emptyRow = makeResult(cell(1, 0), cell(1, 0), cell(1, 0));
emptyColumn = emptyRow.';

selectedRowMask = select_unique_dataset_scan(emptyRow);
selectedColumnMask = select_unique_dataset_scan(emptyColumn);

verifyEqual(testCase, size(selectedRowMask), [1, 0]);
verifyEqual(testCase, size(selectedColumnMask), [0, 1]);
verifyEqual(testCase, class(selectedRowMask), 'logical');
verifyEqual(testCase, class(selectedColumnMask), 'logical');
end

