function testInvalidDatasetNameInputs(testCase)
invalidNames = { ...
        '', ...
        '   ', ...
        101, ...
        {'cell-dataset'}, ...
        ['A'; 'B'], ...
        "string-dataset"};
    for idxName = 1:numel(invalidNames)
        result = makeResult({'dataset-A', 'dataset-A'}, {'1', '2'}, ...
            {'SYNPEPTIDEA', 'SYNPEPTIDEB'});
        result(2).DatasetName = invalidNames{idxName};
        verifyError(testCase, @() select_unique_dataset_scan(result), ...
            'select_unique_dataset_scan:InvalidDatasetName');
    end
end

