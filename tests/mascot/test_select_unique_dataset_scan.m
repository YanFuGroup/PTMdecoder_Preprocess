function testMaskMatchesInlineLegacyReferenceOnMultipleFixtures(testCase)
datasets = { ...
    {'A1', 'A', 'B', 'B', 'C'}, ...
    {'A', 'A', 'D', 'D ', 'E'}, ...
    {'Z', 'Y', 'X', 'W', 'V', 'V'}};
scans = { ...
    {'23', '123', '7', '7', '001'}, ...
    {'001', '1', '2', '2', 'not-a-number'}, ...
    {'1', '1', '1', '1', '1 ', '1'}};
peptides = { ...
    {'SYN1', 'SYN2', 'SYN3', 'SYN4', 'SYN5'}, ...
    {'SYN1', 'SYN2', 'SYN3', 'SYN4', 'SYN5'}, ...
    {'SYN1', 'SYN2', 'SYN3', 'SYN4', 'SYN5', 'SYN6'}};

for idxFixture = 1:numel(datasets)
    result = makeResult(datasets{idxFixture}, scans{idxFixture}, peptides{idxFixture});
    verifyEqual(testCase, select_unique_dataset_scan(result), ...
        inlineLegacyReference(result));
end
end

function testMaskPreservesInputOrderAndDoesNotModifyInput(testCase)
result = makeResult( ...
    {'dataset-Z', 'dataset-A', 'dataset-C', 'dataset-Z'}, ...
    {'300', '001', '20', '300'}, ...
    {'SYNPEPTIDEZ', 'SYNPEPTIDEA', 'SYNPEPTIDEC', 'SYNPEPTIDEZ2'});
originalResult = result;

selectedMask = select_unique_dataset_scan(result);

verifyEqual(testCase, selectedMask, [false, true, true, false]);
verifyEqual(testCase, result, originalResult);
verifyEqual(testCase, {result.peptide}, ...
    {'SYNPEPTIDEZ', 'SYNPEPTIDEA', 'SYNPEPTIDEC', 'SYNPEPTIDEZ2'});
end

function testRowAndColumnInputsReturnSameShape(testCase)
rowResult = makeResult( ...
    {'row-A', 'row-A', 'row-B'}, ...
    {'1', '001', '3'}, ...
    {'SYNPEPTIDEA', 'SYNPEPTIDEB', 'SYNPEPTIDEC'});
columnResult = rowResult.';

rowMask = select_unique_dataset_scan(rowResult);
columnMask = select_unique_dataset_scan(columnResult);

verifyEqual(testCase, size(rowMask), [1, 3]);
verifyEqual(testCase, rowMask, [true, true, true]);
verifyEqual(testCase, size(columnMask), [3, 1]);
verifyEqual(testCase, columnMask, [true; true; true]);
end

