function expectedMask = inlineLegacyReference(result)
legacyKeys = strcat({result.DatasetName}', ' ', {result.Scan}');
[~, ~, groupIndex] = unique(legacyKeys, 'stable');
groupCounts = accumarray(groupIndex, 1);
expectedMask = reshape(groupCounts(groupIndex) == 1, size(result));
end

function result = makeResult(datasetNames, scans, peptides)
template = struct( ...
    'DatasetName', '', ...
    'Scan', '', ...
    'peptide', '', ...
    'Score', 100.5, ...
    'modification', 'Acetyl (K)');
result = repmat(template, size(datasetNames));
for idxResult = 1:numel(datasetNames)
    result(idxResult).DatasetName = datasetNames{idxResult};
    result(idxResult).Scan = scans{idxResult};
    result(idxResult).peptide = peptides{idxResult};
    result(idxResult).Score = 100 + idxResult / 10;
    result(idxResult).modification = sprintf('synthetic-mod-%d', idxResult);
end
end
