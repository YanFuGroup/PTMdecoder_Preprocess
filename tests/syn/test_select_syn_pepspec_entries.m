function tests = test_select_syn_pepspec_entries
tests = functiontests(localfunctions);
addpath(fullfile(fileparts(fileparts(fileparts(mfilename('fullpath')))), 'synthetic'));
end

function testChargeAndMatchedIonPolicies(testCase)
criteria = makeCriteria();
entries = [ ...
    makeEntry('runA', '1', '2', '7'), ...
    makeEntry('runA', '2', '2', '8'), ...
    makeEntry('runB', '2', '2', '8'), ...
    makeEntry('runA', '4', '2', '20'), ...
    makeEntry('runA', '4', '2', '20') ...
];

chargeOnlySelected = select_syn_pepspec_entries(entries, criteria);
criteria.minimumMatchedIons = 8;
matchedIonSelected = select_syn_pepspec_entries(entries, criteria);

verifyEqual(testCase, ...
    strcat({chargeOnlySelected.DatasetName}, ':', {chargeOnlySelected.Scan}), ...
    {'runA:1', 'runA:2', 'runB:2'});
verifyEqual(testCase, ...
    strcat({matchedIonSelected.DatasetName}, ':', {matchedIonSelected.Scan}), ...
    {'runA:2', 'runB:2'});
verifyTrue(testCase, all(strcmp({chargeOnlySelected.Charge}, '2')));
end

function testTargetPeptideMassAndCharge(testCase)
criteria = makeCriteria();
entries = [ ...
    makeEntry('runA', '1', '2', '8'), ...
    setField(makeEntry('runA', '2', '2', '8'), 'peptide', 'OTHERPEPTIDE'), ...
    setField(makeEntry('runA', '3', '2', '8'), 'Calc_neutral_pepmass', '1001'), ...
    makeEntry('runA', '4', '3', '8') ...
];

selected = select_syn_pepspec_entries(entries, criteria);

verifyEqual(testCase, {selected.Scan}, {'1'});
end

function testStrictMassToleranceBoundary(testCase)
criteria = makeCriteria();
criteria.massTolerance = 1;
entries = [ ...
    setField(makeEntry('runA', '1', '2', '8'), ...
        'Calc_neutral_pepmass', '1000.999'), ...
    setField(makeEntry('runA', '2', '2', '8'), ...
        'Calc_neutral_pepmass', '1001'), ...
    setField(makeEntry('runA', '3', '2', '8'), ...
        'Calc_neutral_pepmass', '999'), ...
    setField(makeEntry('runA', '4', '2', '8'), ...
        'Calc_neutral_pepmass', '1001.001') ...
];

selected = select_syn_pepspec_entries(entries, criteria);

verifyEqual(testCase, {selected.Scan}, {'1'});
end

function testNumericMassNearProductionTolerance(testCase)
criteria = makeCriteria();
criteria.massTolerance = 0.0001;
entries = [ ...
    setField(makeEntry('runA', '1', '2', '8'), ...
        'Calc_neutral_pepmass', 1000.0000999), ...
    setField(makeEntry('runA', '2', '2', '8'), ...
        'Calc_neutral_pepmass', 1000.0001001) ...
];

selected = select_syn_pepspec_entries(entries, criteria);

verifyEqual(testCase, {selected.Scan}, {'1'});
end

function testProductionDatasetConfig(testCase)
[indConfig, indCriteria] = syn_pepspec_dataset_config('syn_ind');
[mixConfig, mixCriteria] = syn_pepspec_dataset_config('syn_mix');

verifyEqual(testCase, indConfig, struct('runPrefix', 'ind', 'runCount', 16));
verifyEqual(testCase, mixConfig, struct('runPrefix', 'mix', 'runCount', 18));
verifyEqual(testCase, indCriteria.targetPeptide, 'GKGGKGLGKGGAKR');
verifyEqual(testCase, indCriteria.neutralMass, 1535.878357);
verifyEqual(testCase, indCriteria.massTolerance, 0.0001);
verifyEqual(testCase, indCriteria.charge, 2);
verifyEqual(testCase, indCriteria.minimumMatchedIons, 8);
verifyEqual(testCase, mixCriteria.targetPeptide, 'GKGGKGLGKGGAKR');
verifyEqual(testCase, mixCriteria.neutralMass, 1535.878357);
verifyEqual(testCase, mixCriteria.massTolerance, 0.0001);
verifyEqual(testCase, mixCriteria.charge, 2);
verifyEmpty(testCase, mixCriteria.minimumMatchedIons);
verifyError(testCase, @() syn_pepspec_dataset_config('other'), ...
    'prepare_syn_pepspec:InvalidDataset');
end

function criteria = makeCriteria()
criteria = struct( ...
    'targetPeptide', 'SYNTHETICPEPTIDE', ...
    'neutralMass', 1000, ...
    'massTolerance', 0.01, ...
    'charge', 2, ...
    'minimumMatchedIons', []);
end

function entry = setField(entry, fieldName, value)
entry.(fieldName) = value;
end

function entry = makeEntry(datasetName, scan, charge, matchedIons)
entry = struct( ...
    'Site', 'synthetic', ...
    'DatasetName', datasetName, ...
    'Scan', scan, ...
    'Spectrum', ['spectrum_' scan], ...
    'Charge', charge, ...
    'Calc_neutral_pepmass', '1000', ...
    'precursor_neutral_mass', '1000', ...
    'massdiff', '0', ...
    'num_match_ions', matchedIons, ...
    'peptide', 'SYNTHETICPEPTIDE', ...
    'protein', 'synthetic_protein', ...
    'modification', 'none', ...
    'modificationlocation', 'none', ...
    'Score', '100');
end
